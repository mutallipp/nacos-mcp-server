/** 返回指定语言的文案；未设置或未知语言时使用中文。 */
export function getMessages(language) {
  return Object.hasOwn(CATALOGS, language) ? CATALOGS[language] : CATALOGS["zh-CN"];
}

/** 以命名占位符替换用户可见文案参数。 */
export function message(messages, key, values = {}) {
  return messages[key].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export { CATALOGS };
